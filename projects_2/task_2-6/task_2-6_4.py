choice = input("Куда?(прямо, направо, налево)").lower()
if choice == "налево":
    print("Порядочные витязи не ходят налево. Вы поолучили осуждение общества.")
elif choice == "направо" or choice == "прямо":
    print("Витязь нашёл много денег и остался доволен.")
else:
    print("Витязь ещё не решил. Думает.")
